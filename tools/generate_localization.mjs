// Recognize Kotlin template arguments without damaging nested quoted code.
export function template(s) {
  const parts = [], args = []; let start = 0;
  for (let i = 0; i < s.length; i++) {
    if (s[i] !== '$') continue;
    let end = i + 1, expression;
    if (s[end] === '{') {
      let depth = 1; end++;
      for (let quote = false; end < s.length && depth; end++) {
        if (s[end] === '\\') { end++; continue; }
        if (s[end] === '"') { quote = !quote; continue; }
        if (!quote && s[end] === '{') depth++;
        if (!quote && s[end] === '}') depth--;
      }
      assert.equal(depth, 0); expression = s.slice(i + 2, end - 1);
    } else {
      const name = s.slice(end).match(/^[A-Za-z_]\w*/); if (!name) continue;
      expression = name[0]; end += expression.length;
    }
    parts.push(s.slice(start, i)); args.push({ token: s.slice(i, end), expression });
    parts.push({ arg: args.length }); start = end; i = end - 1;
  }
  parts.push(s.slice(start)); return { parts, args };
}
function format(text, args) {
  const parsed = template(text);
  return parsed.parts.map(p => {
    if (typeof p === 'string') return p;
    const index = args.findIndex(a => a.token === parsed.args[p.arg - 1].token);
    assert.ok(index >= 0, 'Unknown Kotlin interpolation in English');
    return `%${index + 1}$s`;
  }).join('');
}
